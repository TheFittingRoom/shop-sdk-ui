"""Generate src/assets/get-app-qr-code.svg, the QR code on the get-app screen.

Style: teal round modules that just touch their neighbours, black square
finder patterns, and the TFR door (src/assets/tfr-icon.svg) on a teal rounded
square in the centre. Error correction H, so the logo covering the middle
doesn't stop it scanning.

    python3 -m pip install segno==1.6.1
    python3 scripts/make-get-app-qr.py https://www.thefittingroom.tech/download src/assets/get-app-qr-code.svg

Optional args: logo size in modules (odd; default 11) and dot radius as a
fraction of a module (default 0.5). Keep the radius at 0.5: smaller dots
leave gaps that some decoders (jsQR) fail on. Check the result decodes with
a real phone before shipping it.
"""
import sys

import segno

URL = sys.argv[1]
OUT = sys.argv[2]
LOGO_MODULES = int(sys.argv[3]) if len(sys.argv) > 3 else 11

SIZE = 660
TEAL = '#265A64'
BLACK = '#000000'
QUIET = 3  # modules of margin, as in the original

qr = segno.make(URL, error='h', boost_error=False, micro=False)
matrix = [list(row) for row in qr.matrix]
n = len(matrix)
m = SIZE / (n + 2 * QUIET)  # module size in px
origin = QUIET * m


def dark(r, c):
    return 0 <= r < n and 0 <= c < n and bool(matrix[r][c])


# Finder patterns (7x7 at three corners) are drawn separately.
def in_finder(r, c):
    return (r < 7 and c < 7) or (r < 7 and c >= n - 7) or (r >= n - 7 and c < 7)


# Centre logo area, cleared of modules (error correction H restores them).
lo = (n - LOGO_MODULES) // 2
hi = lo + LOGO_MODULES


def in_logo(r, c):
    return lo <= r < hi and lo <= c < hi


def data(r, c):
    return dark(r, c) and not in_finder(r, c) and not in_logo(r, c)


# Separate round modules, sized so neighbours just touch and read as beaded
# chains, as in the original.
rad = m * float(sys.argv[4]) if len(sys.argv) > 4 else m * 0.5
parts = []
for r in range(n):
    for c in range(n):
        if not data(r, c):
            continue
        cx = origin + (c + 0.5) * m
        cy = origin + (r + 0.5) * m
        parts.append(f'<circle cx="{cx:.2f}" cy="{cy:.2f}" r="{rad:.2f}"/>')


def finder(r0, c0):
    x = origin + c0 * m
    y = origin + r0 * m
    # Outer 7x7 ring one module thick, then a 3x3 centre.
    return (
        f'<path fill-rule="evenodd" fill="{BLACK}" d="M{x:.2f},{y:.2f}h{7 * m:.2f}v{7 * m:.2f}h{-7 * m:.2f}z '
        f'M{x + m:.2f},{y + m:.2f}v{5 * m:.2f}h{5 * m:.2f}v{-5 * m:.2f}z"/>'
        f'<rect fill="{BLACK}" x="{x + 2 * m:.2f}" y="{y + 2 * m:.2f}" width="{3 * m:.2f}" height="{3 * m:.2f}" rx="{m * 0.15:.2f}"/>'
    )


# Logo: a rounded square slightly inside the cleared area, with the door
# (src/assets/tfr-icon.svg, viewBox 0 0 12 24) centred in white.
pad = m * 0.1
lx = origin + lo * m + pad
ly = origin + lo * m + pad
ls = LOGO_MODULES * m - 2 * pad
door_h = ls * 0.56
door_scale = door_h / 24
door_w = 12 * door_scale
dx = lx + (ls - door_w) / 2 + door_w * 0.06
dy = ly + (ls - door_h) / 2
DOOR = (
    'M11.9082 4.0752V19.8516L0.161133 22.8545V1.05859L11.9082 4.0752ZM9.31836 10.8525C8.96951 10.8525 '
    '8.68661 11.206 8.68652 11.6416C8.68652 12.0773 8.96946 12.4307 9.31836 12.4307C9.6671 12.4304 9.9502 '
    '12.0771 9.9502 11.6416C9.95011 11.2062 9.66705 10.8528 9.31836 10.8525Z'
)

svg = f'''<svg xmlns="http://www.w3.org/2000/svg" width="{SIZE}" height="{SIZE}" viewBox="0 0 {SIZE} {SIZE}">
<defs>
  <linearGradient id="logoBg" x1="0" y1="0" x2="0" y2="1">
    <stop offset="0" stop-color="#2C5A63"/>
    <stop offset="1" stop-color="#1D3034"/>
  </linearGradient>
</defs>
<g fill="{TEAL}">{''.join(parts)}</g>
{finder(0, 0)}{finder(0, n - 7)}{finder(n - 7, 0)}
<rect x="{lx:.2f}" y="{ly:.2f}" width="{ls:.2f}" height="{ls:.2f}" rx="{ls * 0.2:.2f}" fill="url(#logoBg)"/>
<path transform="translate({dx:.2f} {dy:.2f}) scale({door_scale:.4f})" fill="#FFFFFF" fill-rule="evenodd" d="{DOOR}"/>
</svg>
'''
svg = svg.replace('>', f'>\n<!-- QR code for {URL}. Generated by scripts/make-get-app-qr.py; regenerate rather than edit. -->', 1)
open(OUT, 'w').write(svg)
print(f'version {qr.version}, error {qr.error}, {n}x{n} modules, logo {LOGO_MODULES}x{LOGO_MODULES}')
